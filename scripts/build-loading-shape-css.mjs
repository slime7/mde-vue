import { writeFile } from 'node:fs/promises';
import { createServer } from 'vite';

const vite = await createServer({
  appType: 'custom',
  server: { middlewareMode: true },
});
const {
  DETERMINATE_LOADING_SHAPE_FRAMES,
  formatLoadingPolygon,
  LOADING_SHAPE_ANIMATION_FRAMES,
  LOADING_SHAPE_NAMES,
} = await vite.ssrLoadModule('/src/components/mat-loading/loading-shape-frames.js');

const SHAPE_INTERVAL = 650;
const SHAPE_MORPH_DURATION = 250;
const SHAPE_CYCLE_DURATION = SHAPE_INTERVAL * LOADING_SHAPE_NAMES.length;
const ROTATION_CYCLE_COUNT = 4;
const ROTATION_CYCLE_DURATION = SHAPE_CYCLE_DURATION * ROTATION_CYCLE_COUNT;
const ROTATION_STEP = 90;
const CLAMPED_SPRING_EASING = 'linear(0, .1847 20%, .5274 40%, .8269 60%, 1 80%, 1)';
const SPRING_EASING = 'linear(0, .1847 7.692%, .5274 15.385%, .8269 23.077%, 1.0111 30.769%, 1.0863 38.462%, 1.0906 46.154%, 1.0632 53.846%, 1.031 61.538%, 1.0072 69.231%, .9947 76.923%, .991 84.615%, .9924 92.308%, 1)';

/**
 * @param {number} elapsed
 * @param {number} duration
 * @returns {string}
 */
function percentage(elapsed, duration) {
  return `${Number(((elapsed / duration) * 100).toFixed(6))}%`;
}

/**
 * @param {ReadonlyArray<readonly [number, number]>} frame
 * @returns {string}
 */
function formatPolygon(frame) {
  return formatLoadingPolygon(frame)
    .replace('polygon(', 'polygon(\n        ')
    .replaceAll(', ', ',\n        ')
    .replace(')', '\n      )');
}

/**
 * @param {number} elapsed
 * @param {ReadonlyArray<readonly [number, number]>} frame
 * @param {string | undefined} easing
 * @returns {string}
 */
function shapeKeyframe(elapsed, frame, easing) {
  const timing = easing === undefined
    ? ''
    : `\n      animation-timing-function: ${easing};`;

  return `    ${percentage(elapsed, SHAPE_CYCLE_DURATION)} {\n`
    + `      clip-path: ${formatPolygon(frame)};${timing}\n`
    + '    }';
}

const determinateShapeKeyframes = DETERMINATE_LOADING_SHAPE_FRAMES.map((frame, index) => {
  const framePercentage = index === 0 ? '0%' : '100%';

  return `    ${framePercentage} {\n      clip-path: ${formatPolygon(frame)};\n    }`;
}).join('\n\n');

const shapeKeyframes = [];

for (let index = 0; index < LOADING_SHAPE_NAMES.length; index += 1) {
  const segmentStart = index * SHAPE_INTERVAL;

  shapeKeyframes.push(shapeKeyframe(
    segmentStart,
    LOADING_SHAPE_ANIMATION_FRAMES[index],
    CLAMPED_SPRING_EASING,
  ));
  shapeKeyframes.push(shapeKeyframe(
    segmentStart + SHAPE_MORPH_DURATION,
    LOADING_SHAPE_ANIMATION_FRAMES[index + 1],
    'linear',
  ));
}

shapeKeyframes.push(shapeKeyframe(
  SHAPE_CYCLE_DURATION,
  LOADING_SHAPE_ANIMATION_FRAMES[0],
));

const rotationKeyframes = [];
const rotationSegmentCount = LOADING_SHAPE_NAMES.length * ROTATION_CYCLE_COUNT;

for (let index = 0; index < rotationSegmentCount; index += 1) {
  rotationKeyframes.push(
    `    ${percentage(index * SHAPE_INTERVAL, ROTATION_CYCLE_DURATION)} {\n`
      + `      rotate: ${index * ROTATION_STEP}deg;\n`
      + `      animation-timing-function: ${SPRING_EASING};\n`
      + '    }',
  );
}

rotationKeyframes.push(
  '    100% {\n'
    + `      rotate: ${rotationSegmentCount * ROTATION_STEP}deg;\n`
    + '    }',
);

const css = `/* Generated by scripts/build-loading-shape-css.mjs. */
@layer mde.components {
  @keyframes mat-loading-shape-cycle {
${shapeKeyframes.join('\n\n')}
  }

  @keyframes mat-loading-determinate-shape {
${determinateShapeKeyframes}
  }

  @keyframes mat-loading-morph-rotate {
${rotationKeyframes.join('\n\n')}
  }
}
`;

await writeFile(
  new URL('../src/components/mat-loading/loading-shape-frames.css', import.meta.url),
  css,
  'utf8',
);

await vite.close();
